    private async Task ConfigureTranslationJobsAsync(
        Guid restaurantId,
        TranslationMode translationMode,
        string defaultLocale,
        params (string Code, bool IsEnabled, int SortOrder)[] supportedLocales)
    {
        SetFakeProviderFailure(false);

        using var scope = _factory.Services.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        var settings = await context.RestaurantSettings.SingleAsync(item => item.RestaurantId == restaurantId);
        settings.DefaultLocale = defaultLocale;
        settings.TranslationMode = translationMode;

        foreach (var (code, isEnabled, sortOrder) in supportedLocales)
        {
            var existing = await context.RestaurantSupportedLocales
                .SingleOrDefaultAsync(item => item.RestaurantId == restaurantId && item.LocaleCode == code);
            if (existing is null)
            {
                context.RestaurantSupportedLocales.Add(new RestaurantSupportedLocale
                {
                    RestaurantId = restaurantId,
                    LocaleCode = code,
                    IsEnabled = isEnabled,
                    SortOrder = sortOrder,
                    CreatedAt = DateTime.UtcNow
                });
            }
            else
            {
                existing.IsEnabled = isEnabled;
                existing.SortOrder = sortOrder;
            }
        }

        await context.SaveChangesAsync();
    }

