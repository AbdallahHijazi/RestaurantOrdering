    [Fact]
    public async Task GetRestaurantLocales_AvailableLocalesUseStringDirections()
    {
        await TestDataSeeder.SeedAsync(_factory.Services);
        using var client = CreateHttpsClient();
        await AuthenticateAsync(client, TestDataSeeder.OwnerAEmail, TestDataSeeder.CorrectPassword);

        var response = await client.GetAsync(
            $"/api/v1/admin/restaurants/{TestDataSeeder.RestaurantAId}/locales");

        response.StatusCode.Should().Be(HttpStatusCode.OK);
        var body = await response.Content.ReadAsStringAsync();
        body.Should().Contain("\"direction\":\"rtl\"");
        body.Should().Contain("\"direction\":\"ltr\"");
        body.Should().NotContain("\"direction\":1");
        body.Should().NotContain("\"direction\":2");

        var settings = await response.Content.ReadFromJsonAsync<RestaurantLocaleSettingsResponse>(JsonOptions);
        settings!.AvailableLocales.Select(item => item.Direction)
            .Should()
            .OnlyContain(direction => direction == "rtl" || direction == "ltr");
        settings.AvailableLocales.Single(item => item.Code == "ar").Direction.Should().Be("rtl");
        settings.AvailableLocales.Single(item => item.Code == "en").Direction.Should().Be("ltr");
    }

