    {
        await TestDataSeeder.SeedAsync(_factory.Services);
        using var client = CreateHttpsClient();
        await AuthenticateAsync(client, TestDataSeeder.OwnerAEmail, TestDataSeeder.CorrectPassword);

        var response = await client.GetAsync("/api/v1/system/locales");
        response.StatusCode.Should().Be(HttpStatusCode.OK);

        var locales = await response.Content.ReadFromJsonAsync<List<SystemLocaleResponse>>(JsonOptions);
        locales.Should().NotBeNull();

        var byCode = locales!.ToDictionary(item => item.Code);
        byCode.Should().ContainKeys("ar", "en", "fr", "de");
