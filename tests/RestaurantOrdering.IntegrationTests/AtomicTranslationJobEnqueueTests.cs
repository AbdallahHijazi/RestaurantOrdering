    [Fact]
    public async Task CreateCategory_PersistsEntityPrimaryTranslationAndJobsAtomically()
    {
        await TestDataSeeder.SeedAsync(_factory.Services);
        await ConfigureTranslationJobsAsync(
            TestDataSeeder.RestaurantAId,
            TranslationMode.AutoGenerateDrafts,
            "ar",
            ("ar", true, 1),
            ("en", true, 2),
            ("fr", true, 3));

        using var client = CreateHttpsClient();
        await AuthenticateAsync(client, TestDataSeeder.OwnerAEmail, TestDataSeeder.CorrectPassword);

        var response = await client.PostAsJsonAsync(
            $"/api/v1/admin/restaurants/{TestDataSeeder.RestaurantAId}/catalog/categories",
            CreateCategoryPayload("حلويات", "وصف", 1));

        response.StatusCode.Should().Be(HttpStatusCode.Created);
        var created = await response.Content.ReadFromJsonAsync<CreatedEntityResponse>(JsonOptions);

        using var scope = _factory.Services.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();

        var category = await context.Categories.AsNoTracking()
            .SingleOrDefaultAsync(item => item.Id == created!.Id);
        category.Should().NotBeNull();
        category!.NameAr.Should().Be("حلويات");
        category.ContentVersion.Should().Be(1);

        (await context.CategoryTranslations.AnyAsync(
            item => item.CategoryId == created.Id && item.LocaleCode == "ar" && item.Name == "حلويات"))
            .Should().BeTrue();

        var jobs = await context.TranslationJobs.AsNoTracking()
            .Where(item => item.EntityId == created.Id)
            .ToListAsync();
        jobs.Should().HaveCount(2);
        jobs.Should().OnlyContain(item => item.SourceVersion == 1 && item.Status == TranslationJobStatus.Queued);
    }

