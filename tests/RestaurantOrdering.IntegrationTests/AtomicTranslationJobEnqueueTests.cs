    [Fact]
    public async Task CreateCategory_WhenJobEnqueueFails_DoesNotPersistEntityOrTranslation()
    {
        await TestDataSeeder.SeedAsync(_factory.Services);
        await ConfigureTranslationJobsAsync(
            TestDataSeeder.RestaurantAId,
            TranslationMode.AutoGenerateDrafts,
            "ar",
            ("ar", true, 1),
            ("en", true, 2));

        using var scope = _factory.Services.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        var dateTimeService = scope.ServiceProvider.GetRequiredService<IDateTimeService>();
        var writer = scope.ServiceProvider.GetRequiredService<IPublishedTranslationWriter>();
        var failingEnqueuer = new FailingTranslationJobEnqueuer();
        var handler = new CreateCatalogCategoryCommandHandler(
            context,
            dateTimeService,
            writer,
            failingEnqueuer);

        var categoriesBefore = await context.Categories.CountAsync(item => item.RestaurantId == TestDataSeeder.RestaurantAId);
        var translationsBefore = await context.CategoryTranslations.CountAsync(item =>
            item.Category!.RestaurantId == TestDataSeeder.RestaurantAId);
        var jobsBefore = await context.TranslationJobs.CountAsync(item => item.RestaurantId == TestDataSeeder.RestaurantAId);

        var act = async () => await handler.Handle(
            new CreateCatalogCategoryCommand(
                TestDataSeeder.RestaurantAId,
                "حلويات",
                "وصف",
                1,
                true),
            CancellationToken.None);

        await act.Should().ThrowAsync<InvalidOperationException>()
            .WithMessage("*Simulated translation job enqueue failure*");

        (await context.Categories.CountAsync(item => item.RestaurantId == TestDataSeeder.RestaurantAId))
            .Should().Be(categoriesBefore);
        (await context.CategoryTranslations.CountAsync(item =>
            item.Category!.RestaurantId == TestDataSeeder.RestaurantAId))
            .Should().Be(translationsBefore);
        (await context.TranslationJobs.CountAsync(item => item.RestaurantId == TestDataSeeder.RestaurantAId))
            .Should().Be(jobsBefore);
    }

