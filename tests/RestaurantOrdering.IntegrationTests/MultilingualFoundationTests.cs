    [Fact]
    public async Task DeleteRestaurant_CascadesMultilingualChildren()
    {
        var restaurant = await CreateRestaurantAsync();

        _context.RestaurantSupportedLocales.Add(CreateSupportedLocale(restaurant.Id, "en", 1));
        _context.RestaurantTranslations.Add(CreatePublishedRestaurantTranslation(restaurant.Id, "en", "English Name"));
        _context.TranslationJobs.Add(CreateTranslationJob(restaurant.Id, $"Restaurant:{restaurant.Id}:en:1"));
        _context.TranslationAuditLogs.Add(new TranslationAuditLog
        {
            RestaurantId = restaurant.Id,
            EventType = TranslationAuditEventType.LocaleEnabled,
            CreatedAt = DateTime.UtcNow
        });

        await _context.SaveChangesAsync();

        _context.Restaurants.Remove(restaurant);
        await _context.SaveChangesAsync();

        (await _context.RestaurantSupportedLocales.CountAsync()).Should().Be(0);
        (await _context.RestaurantTranslations.CountAsync()).Should().Be(0);
        (await _context.TranslationJobs.CountAsync()).Should().Be(0);
        (await _context.TranslationAuditLogs.CountAsync()).Should().Be(0);
    }

