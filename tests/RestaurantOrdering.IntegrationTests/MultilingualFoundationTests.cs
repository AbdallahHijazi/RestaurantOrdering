    [Fact]
    public async Task LocaleDefinitions_AreSeededWithExpectedDirections()
    {
        var locales = await _context.LocaleDefinitions
            .AsNoTracking()
            .ToDictionaryAsync(item => item.Code);

        locales.Should().ContainKey("ar");
        locales["ar"].Direction.Should().Be(TextDirection.Rtl);

        locales["en"].Direction.Should().Be(TextDirection.Ltr);
        locales["fr"].Direction.Should().Be(TextDirection.Ltr);
        locales["de"].Direction.Should().Be(TextDirection.Ltr);
    }

