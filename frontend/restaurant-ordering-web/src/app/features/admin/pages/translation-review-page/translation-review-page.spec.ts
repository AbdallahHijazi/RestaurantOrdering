import { provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { ComponentFixture, TestBed } from '@angular/core/testing';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { API_BASE_URL } from '../../../../core/config/api-config';
import { ApplicationRoles } from '../../../../core/auth/application-roles';
import { AuthService } from '../../../../core/auth/auth.service';
import { AuthSessionService } from '../../../../core/auth/auth-session.service';
import { createTestSession } from '../../../../core/auth/test-jwt.util';
import { LocaleService } from '../../../../core/localization/locale';
import type { TranslationReviewApiDto } from '../../data-access/translation-review-api.models';
import { TranslationReviewPage } from './translation-review-page';

const RESTAURANT_ID = 'bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb';

const LOCALE_SETTINGS_RESPONSE = {
  defaultLocale: 'ar',
  translationMode: 'AutoGenerateDrafts',
  supportedLocales: [
    { code: 'ar', isEnabled: true, sortOrder: 1 },
    { code: 'en', isEnabled: true, sortOrder: 2 },
    { code: 'fr', isEnabled: true, sortOrder: 3 },
  ],
  availableLocales: [
    { code: 'ar', displayName: 'Arabic', nativeName: 'العربية', direction: 'rtl' },
    { code: 'en', displayName: 'English', nativeName: 'English', direction: 'ltr' },
    { code: 'fr', displayName: 'French', nativeName: 'Français', direction: 'ltr' },
  ],
  canManageLocales: true,
};

function createItem(overrides: Partial<TranslationReviewApiDto> = {}): TranslationReviewApiDto {
  return {
    translationId: '11111111-1111-1111-1111-111111111111',
    entityType: 'MenuItem',
    entityId: '22222222-2222-2222-2222-222222222222',
    entityDisplayName: 'Burger',
    locale: 'fr',
    draftStatus: 'NeedsReview',
    draftSource: 'Machine',
    draftName: 'Burger FR',
    draftDescription: 'Tasty',
    draftAddress: null,
    publishedName: null,
    publishedDescription: null,
    publishedAddress: null,
    draftSourceVersion: 1,
    currentContentVersion: 1,
    isStale: false,
    canApprove: true,
    canRetry: false,
    updatedAt: '2026-06-13T10:00:00.000Z',
    ...overrides,
  };
}

describe('TranslationReviewPage', () => {
  let fixture: ComponentFixture<TranslationReviewPage>;
  let httpMock: HttpTestingController;
  let session: AuthSessionService;

  beforeEach(async () => {
    TestBed.resetTestingModule();

    await TestBed.configureTestingModule({
      imports: [TranslationReviewPage],
      providers: [provideHttpClient(), provideHttpClientTesting()],
    }).compileComponents();

    httpMock = TestBed.inject(HttpTestingController);
    session = TestBed.inject(AuthSessionService);
    session.clearSession();
    session.saveSession(createTestSession(ApplicationRoles.RestaurantOwner, RESTAURANT_ID));
    TestBed.inject(AuthService).restoreSessionFromStorage();
    TestBed.inject(LocaleService).setLocale('en');

    fixture = TestBed.createComponent(TranslationReviewPage);
  });

  afterEach(() => {
    document.body.classList.remove('order-modal-scroll-lock');
    document.querySelectorAll('app-modal-shell, app-order-modal-shell').forEach((node) => node.remove());
    httpMock.verify({ ignoreCancelled: true });
    session.clearSession();
  });

  function root(): HTMLElement {
    return fixture.nativeElement as HTMLElement;
  }

  function query(testId: string): Element | null {
    return document.body.querySelector(`[data-testid="${testId}"]`) ?? root().querySelector(`[data-testid="${testId}"]`);
  }

  function flushInitialLoad(items: TranslationReviewApiDto[] = [createItem()]): void {
    const localesReq = httpMock.expectOne(
      `${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/locales`,
    );
    localesReq.flush(LOCALE_SETTINGS_RESPONSE);

    const listReq = httpMock.expectOne(
      (request) =>
        request.url ===
          `${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/translations` &&
        request.method === 'GET',
    );
    listReq.flush({ items, page: 1, pageSize: 50, totalCount: items.length });
    fixture.detectChanges();
  }

  it('loads list and renders header, filters, and table', () => {
    const locale = TestBed.inject(LocaleService);
    fixture.detectChanges();
    flushInitialLoad([createItem(), createItem({ translationId: '33333333-3333-3333-3333-333333333333' })]);

    expect(root().textContent).toContain(locale.uiText('translationReviewTitle'));
    expect(root().textContent).toContain(locale.uiText('translationReviewLead'));
    expect(root().querySelector('[data-testid="translation-review-filters"]')).toBeTruthy();
    expect(root().querySelector('[data-testid="translation-review-table"]')).toBeTruthy();
  });

  it('sends locale/entity/status query params when filters change', () => {
    fixture.detectChanges();
    flushInitialLoad([]);

    root().querySelector<HTMLSelectElement>('[data-testid="translation-review-filter-locale"]')!.value = 'fr';
    root()
      .querySelector<HTMLSelectElement>('[data-testid="translation-review-filter-locale"]')!
      .dispatchEvent(new Event('change'));
    fixture.detectChanges();

    const localeReq = httpMock.expectOne(
      (request) =>
        request.url.includes('/translations') && request.params.get('locale') === 'fr',
    );
    localeReq.flush({ items: [], page: 1, pageSize: 50, totalCount: 0 });
    fixture.detectChanges();

    root().querySelector<HTMLSelectElement>('[data-testid="translation-review-filter-entity-type"]')!.value =
      'Category';
    root()
      .querySelector<HTMLSelectElement>('[data-testid="translation-review-filter-entity-type"]')!
      .dispatchEvent(new Event('change'));
    fixture.detectChanges();

    const entityReq = httpMock.expectOne(
      (request) =>
        request.url.includes('/translations') && request.params.get('entityType') === 'Category',
    );
    entityReq.flush({ items: [], page: 1, pageSize: 50, totalCount: 0 });
    fixture.detectChanges();

    root().querySelector<HTMLSelectElement>('[data-testid="translation-review-filter-status"]')!.value =
      'Failed';
    root()
      .querySelector<HTMLSelectElement>('[data-testid="translation-review-filter-status"]')!
      .dispatchEvent(new Event('change'));
    fixture.detectChanges();

    const statusReq = httpMock.expectOne(
      (request) =>
        request.url.includes('/translations') && request.params.get('status') === 'Failed',
    );
    expect(statusReq.request.params.get('locale')).toBe('fr');
    statusReq.flush({ items: [], page: 1, pageSize: 50, totalCount: 0 });
  });

  it('renders entity/status/stale/direction badges', () => {
    fixture.detectChanges();
    flushInitialLoad([
      createItem({
        translationId: 'row-1',
        locale: 'ar',
        isStale: true,
        draftStatus: 'NeedsReview',
      }),
    ]);

    expect(root().querySelector('[data-testid="translation-review-entity-row-1"]')?.textContent).toContain(
      'Menu item',
    );
    expect(root().querySelector('[data-testid="translation-review-status-row-1"]')?.textContent).toContain(
      'Needs review',
    );
    expect(root().querySelector('[data-testid="translation-review-stale-row-1"]')).toBeTruthy();
    expect(root().querySelector('[data-testid="translation-review-locale-row-1"]')?.textContent).toContain(
      'RTL',
    );
  });

  it('opens review modal with published read-only and editable draft fields', () => {
    fixture.detectChanges();
    flushInitialLoad([
      createItem({
        translationId: 'row-edit',
        publishedName: 'Published',
        publishedDescription: 'Pub desc',
      }),
    ]);

    root().querySelector<HTMLButtonElement>('[data-testid="translation-review-edit-row-edit"]')?.click();
    fixture.detectChanges();

    const detailReq = httpMock.expectOne(
      `${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/translations/row-edit`,
    );
    detailReq.flush(
      createItem({
        translationId: 'row-edit',
        publishedName: 'Published',
        publishedDescription: 'Pub desc',
      }),
    );
    fixture.detectChanges();

    expect(query('translation-review-detail')).toBeTruthy();
    expect(query('translation-review-published-name')?.textContent).toContain('Published');
    expect((query('translation-review-draft-name') as HTMLInputElement | null)?.value).toBe('Burger FR');
  });

  it('save draft sends correct payload and refreshes row', () => {
    fixture.detectChanges();
    flushInitialLoad([createItem({ translationId: 'save-row' })]);

    root().querySelector<HTMLButtonElement>('[data-testid="translation-review-edit-save-row"]')?.click();
    fixture.detectChanges();
    httpMock
      .expectOne(`${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/translations/save-row`)
      .flush(createItem({ translationId: 'save-row' }));
    fixture.detectChanges();

    (query('translation-review-draft-name') as HTMLInputElement).value = 'Updated name';
    (query('translation-review-draft-name') as HTMLInputElement).dispatchEvent(new Event('input'));
    fixture.detectChanges();

    (query('translation-review-save-draft') as HTMLButtonElement).click();
    fixture.detectChanges();

    const saveReq = httpMock.expectOne(
      `${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/translations/save-row`,
    );
    expect(saveReq.request.method).toBe('PUT');
    expect(saveReq.request.body).toEqual({
      name: 'Updated name',
      description: 'Tasty',
    });
    saveReq.flush(createItem({ translationId: 'save-row', draftName: 'Updated name' }));
    fixture.detectChanges();

    expect(root().textContent).toContain('Draft saved.');
  });

  it('approve single works only when canApprove and not stale', () => {
    fixture.detectChanges();
    flushInitialLoad([
      createItem({ translationId: 'ok-row', canApprove: true, isStale: false }),
      createItem({
        translationId: 'stale-row',
        canApprove: true,
        isStale: true,
      }),
      createItem({
        translationId: 'blocked-row',
        canApprove: false,
        isStale: false,
      }),
    ]);

    expect(root().querySelector('[data-testid="translation-review-approve-ok-row"]')).toBeTruthy();
    expect(root().querySelector('[data-testid="translation-review-approve-stale-row"]')).toBeNull();
    expect(root().querySelector('[data-testid="translation-review-approve-blocked-row"]')).toBeNull();

    root().querySelector<HTMLButtonElement>('[data-testid="translation-review-approve-ok-row"]')?.click();
    fixture.detectChanges();

    const approveReq = httpMock.expectOne(
      `${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/translations/ok-row/approve`,
    );
    expect(approveReq.request.method).toBe('POST');
    approveReq.flush(createItem({ translationId: 'ok-row', draftStatus: null }));
    fixture.detectChanges();

    const reloadReq = httpMock.expectOne(
      (request) => request.url.includes('/translations') && request.method === 'GET',
    );
    reloadReq.flush({ items: [], page: 1, pageSize: 50, totalCount: 0 });
  });

  it('stale draft hides approve in modal and shows warning', () => {
    fixture.detectChanges();
    flushInitialLoad([createItem({ translationId: 'stale-modal', isStale: true, canApprove: true })]);

    root().querySelector<HTMLButtonElement>('[data-testid="translation-review-edit-stale-modal"]')?.click();
    fixture.detectChanges();
    httpMock
      .expectOne(`${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/translations/stale-modal`)
      .flush(createItem({ translationId: 'stale-modal', isStale: true, canApprove: true }));
    fixture.detectChanges();

    expect(query('translation-review-detail-stale-warning')).toBeTruthy();
    expect(query('translation-review-approve')).toBeNull();
  });

  it('shows retry for failed/canRetry rows and sends retry request', () => {
    fixture.detectChanges();
    flushInitialLoad([
      createItem({ translationId: 'failed-row', draftStatus: 'Failed', canRetry: false }),
      createItem({ translationId: 'retry-row', draftStatus: 'NeedsReview', canRetry: true }),
    ]);

    expect(root().querySelector('[data-testid="translation-review-retry-failed-row"]')).toBeTruthy();
    expect(root().querySelector('[data-testid="translation-review-retry-retry-row"]')).toBeTruthy();

    root().querySelector<HTMLButtonElement>('[data-testid="translation-review-retry-failed-row"]')?.click();
    fixture.detectChanges();

    const retryReq = httpMock.expectOne(
      `${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/translations/failed-row/retry`,
    );
    expect(retryReq.request.method).toBe('POST');
    retryReq.flush(createItem({ translationId: 'failed-row', draftStatus: 'Pending' }));
    fixture.detectChanges();

    expect(root().textContent).toContain('Translation retry started.');
  });

  it('bulk select chooses only approvable non-stale rows', () => {
    fixture.detectChanges();
    flushInitialLoad([
      createItem({ translationId: 'a', canApprove: true }),
      createItem({ translationId: 'b', canApprove: true, isStale: true }),
      createItem({ translationId: 'c', canApprove: false }),
    ]);

    root().querySelector<HTMLInputElement>('[data-testid="translation-review-select-all"]')!.click();
    fixture.detectChanges();

    expect(root().querySelector<HTMLInputElement>('[data-testid="translation-review-select-a"]')?.checked).toBe(
      true,
    );
    expect(root().querySelector<HTMLInputElement>('[data-testid="translation-review-select-b"]')?.disabled).toBe(
      true,
    );
    expect(root().querySelector<HTMLInputElement>('[data-testid="translation-review-select-c"]')?.disabled).toBe(
      true,
    );
  });

  it('bulk approve sends only selectable ids', () => {
    fixture.detectChanges();
    flushInitialLoad([
      createItem({ translationId: 'a', canApprove: true }),
      createItem({ translationId: 'b', canApprove: true, isStale: true }),
    ]);

    root().querySelector<HTMLInputElement>('[data-testid="translation-review-select-all"]')!.click();
    fixture.detectChanges();

    root().querySelector<HTMLButtonElement>('[data-testid="translation-review-bulk-approve"]')!.disabled = false;
    root().querySelector<HTMLButtonElement>('[data-testid="translation-review-bulk-approve"]')?.click();
    fixture.detectChanges();

    const bulkReq = httpMock.expectOne(
      `${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/translations/bulk-approve`,
    );
    expect(bulkReq.request.body).toEqual({ translationIds: ['a'] });
    bulkReq.flush([]);
    fixture.detectChanges();

    httpMock.expectOne((request) => request.url.includes('/translations') && request.method === 'GET').flush({
      items: [],
      page: 1,
      pageSize: 50,
      totalCount: 0,
    });
  });

  it('shows forbidden message on 403 without breaking page', () => {
    fixture.detectChanges();
    flushInitialLoad([createItem({ translationId: 'forbidden-row', canApprove: true })]);

    root().querySelector<HTMLButtonElement>('[data-testid="translation-review-approve-forbidden-row"]')?.click();
    fixture.detectChanges();

    httpMock
      .expectOne(`${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/translations/forbidden-row/approve`)
      .flush({ detail: 'Forbidden' }, { status: 403, statusText: 'Forbidden' });
    fixture.detectChanges();

    expect(root().textContent).toContain('You are not allowed to perform this action.');
    expect(root().querySelector('[data-testid="translation-review-table"]')).toBeTruthy();
  });

  it('renders empty state', () => {
    const locale = TestBed.inject(LocaleService);
    fixture.detectChanges();
    flushInitialLoad([]);

    expect(root().querySelector('[data-testid="translation-review-empty"]')).toBeTruthy();
    expect(root().textContent).toContain(locale.uiText('translationReviewEmptyDescription'));
  });

  it('renders error state with retry', () => {
    fixture.detectChanges();
    httpMock
      .expectOne(`${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/locales`)
      .flush(LOCALE_SETTINGS_RESPONSE);
    httpMock
      .expectOne((request) => request.url.includes('/translations'))
      .flush({ message: 'fail' }, { status: 500, statusText: 'Server Error' });
    fixture.detectChanges();

    expect(root().querySelector('[data-testid="translation-review-error"]')).toBeTruthy();
    root().querySelector<HTMLButtonElement>('[data-testid="translation-review-retry-load"]')?.click();
    fixture.detectChanges();

    httpMock
      .expectOne(`${API_BASE_URL}/api/v1/admin/restaurants/${RESTAURANT_ID}/locales`)
      .flush(LOCALE_SETTINGS_RESPONSE);
    httpMock
      .expectOne((request) => request.url.includes('/translations'))
      .flush({ items: [createItem()], page: 1, pageSize: 50, totalCount: 1 });
    fixture.detectChanges();

    expect(root().querySelector('[data-testid="translation-review-table"]')).toBeTruthy();
  });

  it('uses direction from metadata and fallback without hardcoded locale checks', () => {
    fixture.detectChanges();
    flushInitialLoad([
      createItem({ translationId: 'fr-row', locale: 'fr' }),
      createItem({ translationId: 'ar-row', locale: 'ar' }),
    ]);

    expect(root().querySelector('[data-testid="translation-review-locale-fr-row"]')?.textContent).toContain(
      'LTR',
    );
    expect(root().querySelector('[data-testid="translation-review-locale-ar-row"]')?.textContent).toContain(
      'RTL',
    );
  });

  it('renders missing restaurant context state', () => {
    fixture.destroy();

    session.clearSession();
    TestBed.inject(AuthService).restoreSessionFromStorage();
    fixture = TestBed.createComponent(TranslationReviewPage);
    fixture.detectChanges();

    expect(query('translation-review-missing-context')).toBeTruthy();
  });

  it('keeps admin UI text available in Arabic and English only keys', () => {
    fixture.destroy();

    const locale = TestBed.inject(LocaleService);
    locale.setLocale('ar');
    expect(locale.uiText('translationReviewTitle')).toBe('مراجعة الترجمات');
    locale.setLocale('en');
    expect(locale.uiText('translationReviewTitle')).toBe('Translation Review');
  });
});
