using System.Text.Json;
using FluentValidation;
using MediatR;
using Microsoft.EntityFrameworkCore;
using RestaurantOrdering.Application.Common.Exceptions;
using RestaurantOrdering.Application.Common.Interfaces;
using RestaurantOrdering.Application.Common.Security;
using RestaurantOrdering.Application.Features.Locales.Common;
using RestaurantOrdering.Application.Features.Locales.DTOs;
using RestaurantOrdering.Application.Features.Locales.Queries.GetRestaurantLocaleSettings;
using RestaurantOrdering.Domain.Entities;
using RestaurantOrdering.Domain.Enums;

namespace RestaurantOrdering.Application.Features.Locales.Commands.UpdateRestaurantLocaleSettings;

public sealed class UpdateRestaurantLocaleSettingsCommandHandler
    : IRequestHandler<UpdateRestaurantLocaleSettingsCommand, RestaurantLocaleSettingsDto>
{
    private readonly IApplicationDbContext _context;
    private readonly ICurrentUserService _currentUserService;
    private readonly IRestaurantPermissionService _permissionService;
    private readonly IDateTimeService _dateTimeService;
    private readonly ISender _sender;

    public UpdateRestaurantLocaleSettingsCommandHandler(
        IApplicationDbContext context,
        ICurrentUserService currentUserService,
        IRestaurantPermissionService permissionService,
        IDateTimeService dateTimeService,
        ISender sender)
    {
        _context = context;
        _currentUserService = currentUserService;
        _permissionService = permissionService;
        _dateTimeService = dateTimeService;
        _sender = sender;
    }

    public async Task<RestaurantLocaleSettingsDto> Handle(
        UpdateRestaurantLocaleSettingsCommand request,
        CancellationToken cancellationToken)
    {
        var restaurantExists = await _context.Restaurants
            .AnyAsync(restaurant => restaurant.Id == request.RestaurantId && !restaurant.IsDeleted, cancellationToken);

        if (!restaurantExists)
        {
            throw new NotFoundException("Restaurant", request.RestaurantId);
        }

        var userId = _currentUserService.UserId
            ?? throw new UnauthorizedAccessException("Authentication is required.");

        await _permissionService.EnsurePermissionAsync(
            userId,
            request.RestaurantId,
            RestaurantPermission.RestaurantSettingsManageLocales,
            cancellationToken);

        ValidateSupportedLocaleStructure(request);
        await ValidateLocaleDefinitionsAsync(request, cancellationToken);

        if (!TranslationModeParser.TryParse(request.TranslationMode, out var translationMode))
        {
            throw new ValidationException(new[]
            {
                new FluentValidation.Results.ValidationFailure(
                    nameof(request.TranslationMode),
                    "TranslationMode must be ManualOnly, AutoGenerateDrafts, or AutoPublish.")
            });
        }

        var settings = await _context.RestaurantSettings
            .SingleAsync(item => item.RestaurantId == request.RestaurantId, cancellationToken);

        var previousDefaultLocale = settings.DefaultLocale;
        var previousTranslationMode = settings.TranslationMode;
        var normalizedDefaultLocale = request.DefaultLocale.Trim();

        TransitionalPrimaryLocaleGuard.EnsureAllowedDefaultLocale(normalizedDefaultLocale);

        if (!string.Equals(previousDefaultLocale, normalizedDefaultLocale, StringComparison.Ordinal))
        {
            var missingCounts = await PrimaryLocaleTranslationValidator.GetMissingCountsAsync(
                _context,
                request.RestaurantId,
                normalizedDefaultLocale,
                cancellationToken);

            if (missingCounts is not null)
            {
                throw PrimaryLocaleTranslationValidator.CreateValidationException(missingCounts);
            }
        }

        var existingSupportedLocales = await _context.RestaurantSupportedLocales
            .Where(item => item.RestaurantId == request.RestaurantId)
            .ToDictionaryAsync(item => item.LocaleCode, StringComparer.Ordinal, cancellationToken);

        var now = _dateTimeService.UtcNow;
        var auditLogs = new List<TranslationAuditLog>();

        foreach (var requestedLocale in request.SupportedLocales)
        {
            var normalizedCode = requestedLocale.Code.Trim();

            if (existingSupportedLocales.TryGetValue(normalizedCode, out var existingLocale))
            {
                if (existingLocale.IsEnabled != requestedLocale.IsEnabled)
                {
                    auditLogs.Add(CreateAuditLog(
                        request.RestaurantId,
                        userId,
                        requestedLocale.IsEnabled
                            ? TranslationAuditEventType.LocaleEnabled
                            : TranslationAuditEventType.LocaleDisabled,
                        normalizedCode,
                        now));
                }

                existingLocale.IsEnabled = requestedLocale.IsEnabled;
                existingLocale.SortOrder = requestedLocale.SortOrder;
            }
            else
            {
                _context.RestaurantSupportedLocales.Add(new RestaurantSupportedLocale
                {
                    RestaurantId = request.RestaurantId,
                    LocaleCode = normalizedCode,
                    IsEnabled = requestedLocale.IsEnabled,
                    SortOrder = requestedLocale.SortOrder,
                    CreatedAt = now
                });

                if (requestedLocale.IsEnabled)
                {
                    auditLogs.Add(CreateAuditLog(
                        request.RestaurantId,
                        userId,
                        TranslationAuditEventType.LocaleEnabled,
                        normalizedCode,
                        now));
                }
            }
        }

        if (!string.Equals(previousDefaultLocale, normalizedDefaultLocale, StringComparison.Ordinal))
        {
            settings.DefaultLocale = normalizedDefaultLocale;
            auditLogs.Add(CreateAuditLog(
                request.RestaurantId,
                userId,
                TranslationAuditEventType.PrimaryLocaleChanged,
                normalizedDefaultLocale,
                now,
                JsonSerializer.Serialize(new
                {
                    from = previousDefaultLocale,
                    to = normalizedDefaultLocale
                })));
        }

        if (previousTranslationMode != translationMode)
        {
            settings.TranslationMode = translationMode;
            auditLogs.Add(CreateAuditLog(
                request.RestaurantId,
                userId,
                TranslationAuditEventType.TranslationModeChanged,
                localeCode: null,
                now,
                JsonSerializer.Serialize(new
                {
                    from = TranslationModeParser.ToApiValue(previousTranslationMode),
                    to = TranslationModeParser.ToApiValue(translationMode)
                })));
        }

        settings.UpdatedAt = now;

        if (auditLogs.Count > 0)
        {
            _context.TranslationAuditLogs.AddRange(auditLogs);
        }

        await _context.SaveChangesAsync(cancellationToken);

        return await _sender.Send(new GetRestaurantLocaleSettingsQuery(request.RestaurantId), cancellationToken);
    }

    private static void ValidateSupportedLocaleStructure(UpdateRestaurantLocaleSettingsCommand request)
    {
        var failures = new List<FluentValidation.Results.ValidationFailure>();
        var normalizedDefaultLocale = request.DefaultLocale.Trim();
        var supportedLocales = request.SupportedLocales
            .Select(item => new
            {
                Code = item.Code.Trim(),
                item.IsEnabled,
                item.SortOrder
            })
            .ToList();

        if (supportedLocales.Any(item => string.IsNullOrWhiteSpace(item.Code)))
        {
            failures.Add(new FluentValidation.Results.ValidationFailure(
                nameof(request.SupportedLocales),
                "Supported locale codes cannot be empty."));
        }

        var duplicateCodes = supportedLocales
            .GroupBy(item => item.Code, StringComparer.Ordinal)
            .Where(group => group.Count() > 1)
            .Select(group => group.Key)
            .ToList();

        if (duplicateCodes.Count > 0)
        {
            failures.Add(new FluentValidation.Results.ValidationFailure(
                nameof(request.SupportedLocales),
                $"Duplicate locale codes are not allowed: {string.Join(", ", duplicateCodes)}."));
        }

        var defaultLocaleEntry = supportedLocales
            .FirstOrDefault(item => string.Equals(item.Code, normalizedDefaultLocale, StringComparison.Ordinal));

        if (defaultLocaleEntry is null)
        {
            failures.Add(new FluentValidation.Results.ValidationFailure(
                nameof(request.DefaultLocale),
                "Default locale must be included in supportedLocales."));
        }
        else if (defaultLocaleEntry is { IsEnabled: false })
        {
            failures.Add(new FluentValidation.Results.ValidationFailure(
                nameof(request.DefaultLocale),
                "Default locale cannot be disabled."));
        }

        if (failures.Count > 0)
        {
            throw new ValidationException(failures);
        }
    }

    private async Task ValidateLocaleDefinitionsAsync(
        UpdateRestaurantLocaleSettingsCommand request,
        CancellationToken cancellationToken)
    {
        var codes = request.SupportedLocales
            .Select(item => item.Code.Trim())
            .Where(item => !string.IsNullOrWhiteSpace(item))
            .Distinct(StringComparer.Ordinal)
            .ToList();

        if (codes.Count == 0)
        {
            return;
        }

        var definitions = await _context.LocaleDefinitions
            .AsNoTracking()
            .Where(locale => codes.Contains(locale.Code))
            .ToDictionaryAsync(locale => locale.Code, StringComparer.Ordinal, cancellationToken);

        var failures = new List<FluentValidation.Results.ValidationFailure>();

        foreach (var code in codes)
        {
            if (!definitions.TryGetValue(code, out var definition))
            {
                failures.Add(new FluentValidation.Results.ValidationFailure(
                    nameof(request.SupportedLocales),
                    $"Locale '{code}' is not defined."));
                continue;
            }

            if (!definition.IsEnabled)
            {
                failures.Add(new FluentValidation.Results.ValidationFailure(
                    nameof(request.SupportedLocales),
                    $"Locale '{code}' is disabled system-wide."));
            }
        }

        if (failures.Count > 0)
        {
            throw new ValidationException(failures);
        }
    }

    private static TranslationAuditLog CreateAuditLog(
        Guid restaurantId,
        Guid actorUserId,
        TranslationAuditEventType eventType,
        string? localeCode,
        DateTime createdAt,
        string? payloadJson = null) =>
        new()
        {
            RestaurantId = restaurantId,
            ActorUserId = actorUserId,
            EventType = eventType,
            LocaleCode = localeCode,
            PayloadJson = payloadJson,
            CreatedAt = createdAt
        };
}
